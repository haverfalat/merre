// Render the existing railway font as map sprites. Native and web map engines
// share these assets, so MNR symbols do not depend on a third-party glyph server.
import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';
import sharp from 'sharp';
const directory = fileURLToPath(new URL('../assets/map-glyphs/', import.meta.url));
await fs.mkdir(directory, { recursive: true });
const data = await fs.readFile(new URL('../assets/fonts/MNR2007.ttf', import.meta.url));
const font = opentype.parse(data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength));
const entries = []; const metrics = {};
function distanceField(alpha, width, height) {
  const inside = new Float64Array(width * height), outside = new Float64Array(width * height);
  for (let i = 0; i < alpha.length; i++) { inside[i] = alpha[i] >= 128 ? 1e6 : 0; outside[i] = alpha[i] >= 128 ? 0 : 1e6; }
  for (const values of [inside, outside]) {
    for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) { const i = y * width + x;
      if (x) values[i] = Math.min(values[i], values[i - 1] + 1);
      if (y) values[i] = Math.min(values[i], values[i - width] + 1, x ? values[i - width - 1] + Math.SQRT2 : 1e6, x < width - 1 ? values[i - width + 1] + Math.SQRT2 : 1e6);
    }
    for (let y = height - 1; y >= 0; y--) for (let x = width - 1; x >= 0; x--) { const i = y * width + x;
      if (x < width - 1) values[i] = Math.min(values[i], values[i + 1] + 1);
      if (y < height - 1) values[i] = Math.min(values[i], values[i + width] + 1, x ? values[i + width - 1] + Math.SQRT2 : 1e6, x < width - 1 ? values[i + width + 1] + Math.SQRT2 : 1e6);
    }
  }
  const rgba = Buffer.alloc(width * height * 4, 255);
  for (let i = 0; i < alpha.length; i++) { const signed = inside[i] - outside[i]; rgba[i * 4 + 3] = Math.max(0, Math.min(255, Math.round(255 * (0.75 + (signed - Math.sign(signed) * 0.5) / 8)))); }
  return rgba;
}
for (const code of Object.keys(font.tables.cmap.glyphIndexMap).map(Number).filter((code) => code > 32 && code < 65535)) {
  const glyph = font.charToGlyph(String.fromCodePoint(code));
  const box = glyph.getBoundingBox(); const size = 48; const scale = size / font.unitsPerEm;
  if (!Number.isFinite(box.x1) || box.x1 === box.x2) continue;
  // Never squeeze wide railway emblems into a square or crop their contours.
  // All images retain the same font scale; their dimensions follow the outline.
  const padding = 10;
  const width = Math.ceil((box.x2 - box.x1) * scale) + padding * 2;
  const height = Math.ceil((box.y2 - box.y1) * scale) + padding * 2;
  const x = (width - (box.x2 - box.x1) * scale) / 2 - box.x1 * scale;
  const y = (height - (box.y2 - box.y1) * scale) / 2 + box.y2 * scale;
  // Serialize rounded coordinates directly: opentype's decimal formatter can
  // emit NaN for floating-point values extremely close to an integer.
  const path = glyph.getPath(x, y, size).commands.map((command) => {
    const axes = { M: ['x', 'y'], L: ['x', 'y'], Q: ['x1', 'y1', 'x', 'y'], C: ['x1', 'y1', 'x2', 'y2', 'x', 'y'], Z: [] }[command.type];
    return command.type + axes.map((axis) => Number(command[axis].toFixed(3))).join(' ');
  }).join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}"><path d="${path}" fill="white"/></svg>`;
  const alpha = await sharp(Buffer.from(svg)).ensureAlpha().extractChannel('alpha').raw().toBuffer();
  await sharp(distanceField(alpha, width, height), { raw: { width, height, channels: 4 } }).png().toFile(`${directory}/${code}.png`);
  metrics[`mnr-${code}`] = { advance: (glyph.advanceWidth || font.unitsPerEm) / font.unitsPerEm * 12, left: box.x1 / font.unitsPerEm * 12, width: (box.x2 - box.x1) / font.unitsPerEm * 12 };
  entries.push(`  'mnr-${code}': require('../../../assets/map-glyphs/${code}.png'),`);
}
await fs.writeFile(new URL('../src/features/map/glyph-assets.ts', import.meta.url), `// Generated by npm run assets:glyphs from the original MNR2007 font.\nexport const glyphAssets: Record<string, number> = {\n${entries.join('\n')}\n};\n`);
await fs.writeFile(new URL('../src/features/map/glyph-metrics.json', import.meta.url), JSON.stringify(metrics));
console.log(`Generated ${entries.length} railway glyphs.`);
